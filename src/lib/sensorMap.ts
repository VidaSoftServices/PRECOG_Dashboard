import { findKnownMetric, type ImportCatalog } from '@/lib/sensorImport';

/**
 * Builds the text of the Vibration_Duo firmware's `include/sensor_map.h` from the Sensors that exist on a Device right
 * now: one `#define PRECOG_SENSOR_ID_<TAG> <id>` per firmware channel, with the numeric, Device-scoped SensorId the API
 * reports. Pure and unit-tested; no React, no I/O.
 *
 * A firmware channel is a known metric of the API catalog (`{machineName}_{point}`) of measurement point 1 or 2 - the
 * firmware has two WTVB02 units and two IR inputs. Any other Sensor (a custom tag, point 3, ...) is not a firmware channel
 * and is only listed in a comment. Ids are never guessed or renumbered: they are exactly what the API returned, in
 * ascending id order. A channel that has no Sensor is simply absent (the firmware's defaults file leaves it 0 = unmapped).
 */

/** The measurement points the firmware has (WTVB02 #1/#2 and IR input #1/#2). */
export const FIRMWARE_POINTS = [1, 2] as const;

export interface SensorMapSensor {
  id: number;
  externalSensorId: string;
}

export interface SensorMapInfo {
  deviceId: number;
  deviceName: string;
  externalDeviceId: string;
  generatedAt: Date;
}

export interface SensorMapResult {
  /** The complete file content, ready to be saved as `sensor_map.h`. */
  text: string;
  /** Number of `#define` lines. */
  mapped: number;
  /** Sensors that are not firmware channels, with the reason. */
  skipped: { externalSensorId: string; reason: string }[];
  /** Firmware channels (catalog metric x point 1|2) that have no Sensor on the Device. */
  missing: string[];
}

/** The firmware's macro for a channel: `PRECOG_SENSOR_ID_` + the External Sensor ID in upper case. */
export function sensorMacroName(externalSensorId: string): string {
  return `PRECOG_SENSOR_ID_${externalSensorId.toUpperCase()}`;
}

/** At most this many names are spelled out in a comment; the rest is a count. */
const LISTED = 20;

function listed(names: string[]): string {
  return names.length <= LISTED ? names.join(', ') : `${names.slice(0, LISTED).join(', ')} ... and ${names.length - LISTED} more`;
}

export function buildSensorMap(sensors: SensorMapSensor[], catalog: ImportCatalog, info: SensorMapInfo): SensorMapResult {
  const ordered = [...sensors].sort((a, b) => a.id - b.id);
  const firmwareTag = (tag: string): boolean => {
    const match = findKnownMetric(catalog, tag);
    return match !== undefined && (FIRMWARE_POINTS as readonly number[]).includes(Number(tag.slice(match.machineName.length + 1)));
  };

  const mapped = ordered.filter((s) => firmwareTag(s.externalSensorId));
  const skipped = ordered
    .filter((s) => !firmwareTag(s.externalSensorId))
    .map((s) => ({
      externalSensorId: s.externalSensorId,
      reason: findKnownMetric(catalog, s.externalSensorId) ? 'the firmware has only measurement points 1 and 2' : 'not a Vibration_Duo channel name',
    }));

  const present = new Set(mapped.map((s) => s.externalSensorId));
  const expected = catalog.metrics.flatMap((m) => FIRMWARE_POINTS.map((p) => `${m.machineName}_${p}`));
  const missing = expected.filter((tag) => !present.has(tag));

  const width = Math.max(...mapped.map((s) => String(s.id).length), 3);
  const nameWidth = Math.max(...mapped.map((s) => sensorMacroName(s.externalSensorId).length), 58);

  const lines: string[] = [
    '// External Sensor ID -> numeric SensorId mapping - generated by the PRECOG dashboard.',
    '//',
    `// Device: ${info.deviceName || info.externalDeviceId} (id ${info.deviceId}, external id ${info.externalDeviceId}).`,
    `// Generated ${info.generatedAt.toISOString()} from the Sensors that exist on the Device at that moment.`,
    `// ${mapped.length} of ${expected.length} firmware channels have a Sensor; the others are left out and stay 0 = not mapped`,
    '// (include/sensor_map_defaults.h supplies the default), so the firmware never sends for them and never invents an id.',
    '//',
    '// Save this as include/sensor_map.h of the Vibration_Duo firmware (the file is gitignored). The ids are exactly what the',
    '// API reports; if Sensors are deleted and created again their ids change - export again.',
  ];
  if (missing.length > 0) lines.push('//', `// No Sensor yet (${missing.length}): ${listed(missing)}`);
  if (skipped.length > 0) lines.push('//', `// Skipped, not a firmware channel (${skipped.length}): ${listed(skipped.map((s) => `${s.externalSensorId} (${s.reason})`))}`);
  lines.push('#pragma once', '', '// clang-format off');
  for (const s of mapped) {
    lines.push(`#define ${sensorMacroName(s.externalSensorId).padEnd(nameWidth)} ${String(s.id).padStart(width)}   /* ${s.externalSensorId} */`);
  }
  lines.push('// clang-format on', '');

  return { text: lines.join('\n'), mapped: mapped.length, skipped, missing };
}

/** The file name offered for the download. */
export function sensorMapFileName(deviceId: number): string {
  return `sensor_map-device-${deviceId}.txt`;
}
