import { deviceFilePart } from './deviceFileName';
/**
 * Builds the text of the Vibration_Duo firmware's `include/sensor_map.h` from the Sensors that exist on a Device right
 * now: one `#define PRECOG_SENSOR_ID_<TAG> <id>` per Sensor, with the numeric, Device-scoped SensorId the API reports.
 * Pure and unit-tested; no React, no I/O.
 *
 * Nothing is filtered and nothing is compared with a catalog (2026-11-24, the user's rule): every Sensor of the Device is
 * exported, whatever its name, because the person who made the Sensor knows what the firmware does with it. Ids are never
 * guessed or renumbered: they are exactly what the API returned, in ascending id order. A Sensor that does not exist is
 * simply absent (the firmware's defaults file leaves it 0 = unmapped).
 */

export interface SensorMapSensor {
  id: number;
  externalSensorId: string;
}

export interface SensorMapInfo {
  deviceId: number;
  deviceName: string;
  externalDeviceId: string;
  generatedAt: Date;
}

export interface SensorMapResult {
  /** The complete file content, ready to be saved as `sensor_map.h`. */
  text: string;
  /** Number of `#define` lines (= the Sensors of the Device). */
  mapped: number;
}

/**
 * The firmware's macro for a Sensor: `PRECOG_SENSOR_ID_` + the External Sensor ID in upper case. A character that cannot be
 * part of a C identifier (a space, a dash, a dot, ...) becomes `_`, so the header always compiles; the original name stays
 * in the comment after the number.
 */
export function sensorMacroName(externalSensorId: string): string {
  return `PRECOG_SENSOR_ID_${externalSensorId.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}`;
}

export function buildSensorMap(sensors: SensorMapSensor[], info: SensorMapInfo): SensorMapResult {
  const ordered = [...sensors].sort((a, b) => a.id - b.id);

  const width = Math.max(...ordered.map((s) => String(s.id).length), 3);
  const nameWidth = Math.max(...ordered.map((s) => sensorMacroName(s.externalSensorId).length), 58);

  const lines: string[] = [
    '// External Sensor ID -> numeric SensorId mapping - generated by the PRECOG dashboard.',
    '//',
    `// Device: ${info.deviceName || info.externalDeviceId} (id ${info.deviceId}, external id ${info.externalDeviceId}).`,
    `// Generated ${info.generatedAt.toISOString()} from the Sensors that exist on the Device at that moment.`,
    `// ${ordered.length} Sensors, all of them exported; a Sensor that does not exist is left out and stays 0 = not mapped`,
    '// (include/sensor_map_defaults.h supplies the default), so the firmware never sends for it and never invents an id.',
    '//',
    '// Save this as include/sensor_map.h of the Vibration_Duo firmware (the file is gitignored). The ids are exactly what the',
    '// API reports; if Sensors are deleted and created again their ids change - export again.',
    '#pragma once',
    '',
    '// clang-format off',
  ];
  for (const s of ordered) {
    lines.push(`#define ${sensorMacroName(s.externalSensorId).padEnd(nameWidth)} ${String(s.id).padStart(width)}   /* ${s.externalSensorId} */`);
  }
  lines.push('// clang-format on', '');

  return { text: lines.join('\n'), mapped: ordered.length };
}

/** The file name of the download: the Device's number and its name, e.g. "sensor_map-device-2-KS4.txt". */
export function sensorMapFileName(deviceId: number, deviceName?: string | null): string {
  return `sensor_map-${deviceFilePart(deviceId, deviceName)}.txt`;
}
